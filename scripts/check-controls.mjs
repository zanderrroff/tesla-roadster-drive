import assert from 'node:assert/strict'
import {driveForces,canSelectGear} from '../src/driving.ts'
assert.ok(driveForces(true,true,false,false,'D',0).force<0)
assert.ok(driveForces(true,true,false,false,'R',0).force>0)
assert.equal(driveForces(true,true,false,false,'N',0).force,0)
assert.equal(driveForces(true,true,true,false,'D',10).force,0)
assert.deepEqual(driveForces(true,true,false,true,'R',0),{force:0,frontBrake:18,rearBrake:18})
assert.deepEqual(driveForces(true,true,false,true,'D',20),{force:0,frontBrake:0,rearBrake:18})
assert.equal(driveForces(false,true,false,false,'D',0).force,0)
assert.equal(canSelectGear('D','R',12),false)
assert.equal(canSelectGear('R','D',-5),false)
assert.equal(canSelectGear('D','N',12),true)
assert.equal(canSelectGear('D','R',0),true)
console.log('11 drivetrain and gear safety regression assertions passed')
const {pedalIntent}=await import('../src/driving.ts')
assert.deepEqual(pedalIntent(false,true,15,0,true,'D'),{throttle:false,brake:true,gear:'D'})
assert.deepEqual(pedalIntent(false,true,0,.2,true,'D'),{throttle:false,brake:true,gear:'D'})
assert.deepEqual(pedalIntent(false,true,0,.4,true,'D'),{throttle:true,brake:false,gear:'R'})
assert.deepEqual(pedalIntent(true,false,-3,0,true,'R'),{throttle:false,brake:true,gear:'R'})
assert.deepEqual(pedalIntent(true,false,0,0,true,'R'),{throttle:true,brake:false,gear:'D'})
assert.equal(pedalIntent(false,true,0,1,false,'D').gear,'D')
assert.equal(pedalIntent(true,true,10,0,true,'D').throttle,false)
console.log('Automatic reverse and opposing-pedal regressions passed')
