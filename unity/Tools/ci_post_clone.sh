#!/bin/sh
set -eu
# This runs in Xcode Cloud AFTER Unity has exported the generated project.
# The generated branch contains UnityFramework/IL2CPP output; no Unity login is used here.
if [ ! -d "${CI_PRIMARY_REPOSITORY_PATH}/Unity-iPhone.xcodeproj" ]; then
  echo 'This workflow must use the ios-xcode-export branch generated by Unity.' >&2
  exit 1
fi
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion ${CI_BUILD_NUMBER}" "${CI_PRIMARY_REPOSITORY_PATH}/Info.plist"
echo "Motor Coast Xcode Cloud build ${CI_BUILD_NUMBER}"
